const GENERATED_DIRS = ['web/js/api/generated', 'tests/contracts/generated'];
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const HEADER = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by scripts/quality/contracts.mjs; do not edit.\n';
const METHODS = new Set(['get','put','post','delete','patch','options','head','trace']);
const pointerTokens = fragment => decodeURIComponent(fragment).replace(/^\//, '').split('/').map(x => x.replace(/~1/g,'/').replace(/~0/g,'~'));
const pointerEscape = token => token.replace(/~/g,'~0').replace(/\//g,'~1');
const digest = text => createHash('sha256').update(text).digest('hex');
const inside = (base, file) => file === base || file.startsWith(base + path.sep);

/** Only local refs inside docs/api are allowed; resolve every ref, even annotations. */
export async function loadContract(root = ROOT) {
  const base = await fs.realpath(path.join(root, 'docs/api'));
  const entry = path.join(base, 'openapi.yaml');
  const documents = new Map();
  const sources = {};
  async function read(file) {
    if (!inside(base,file)) throw Error(`Contract ref escapes docs/api: ${file}`);
    const real = await fs.realpath(file);
    if (!inside(base,real)) throw Error(`Contract symlink escapes docs/api: ${file}`);
    if (documents.has(file)) return documents.get(file);
    const text = await fs.readFile(file, 'utf8');
    const doc = YAML.parse(text, { uniqueKeys: true });
    if (!doc || typeof doc !== 'object') throw Error(`Invalid contract document: ${file}`);
    documents.set(file,doc);
    sources[path.relative(root,file).split(path.sep).join('/')] = digest(text);
    await visit(doc,file);
    return doc;
  }
  async function resolve(ref, file) {
    if (typeof ref !== 'string' || /^(?:[a-z][a-z0-9+.-]*:|\/)/i.test(ref)) throw Error(`Only local contract refs are allowed: ${ref}`);
    const index = ref.indexOf('#');
    const targetPath = index < 0 ? ref : ref.slice(0,index);
    const fragment = index < 0 ? '' : ref.slice(index+1);
    if (fragment && !fragment.startsWith('/')) throw Error(`Unsupported non-pointer ref: ${ref}`);
    const targetFile = targetPath ? path.resolve(path.dirname(file),decodeURIComponent(targetPath)) : file;
    let target = await read(targetFile);
    const tokens = fragment ? pointerTokens(fragment) : [];
    for (const token of tokens) {
      if (!target || typeof target !== 'object' || !Object.hasOwn(target,token)) throw Error(`Unresolved ref ${ref} in ${file}`);
      target=target[token];
    }
    return { target, targetFile, tokens };
  }
  async function visit(value,file) {
    if (!value || typeof value !== 'object') return;
    if (Object.hasOwn(value,'$ref')) await resolve(value.$ref,file);
    for (const child of Object.values(value)) await visit(child,file);
  }
  const document = await read(entry);
  if (!/^3\.1\./.test(document.openapi ?? '')) throw Error('OpenAPI 3.1 is required');
  if (document.jsonSchemaDialect !== 'https://spec.openapis.org/oas/3.1/dialect/base') throw Error('Unexpected OpenAPI schema dialect');
  async function normalize(value,file,chain = new Set()) {
    if (Array.isArray(value)) return Promise.all(value.map(x=>normalize(x,file,chain)));
    if (!value || typeof value !== 'object') return value;
    const result = {};
    for (const [key,child] of Object.entries(value)) {
      if (key !== '$ref') { result[key] = await normalize(child,file,chain); continue; }
      const { target,targetFile,tokens } = await resolve(child,file);
      if (tokens[0] === 'components' && tokens.length >= 3) {
        result.$ref = '#/' + tokens.map(pointerEscape).join('/');
      } else if (tokens[0] === 'paths' && tokens.length === 2) {
        const identity=targetFile+'#'+tokens.join('/');
        if(chain.has(identity)) throw Error(`Cyclic Path Item ref: ${child}`);
        Object.assign(result,await normalize(target,targetFile,new Set([...chain,identity])));
      } else throw Error(`Ref must target components or a Path Item: ${child}`);
    }
    return result;
  }
  const contract = await normalize(document,entry);
  contract.components = {};
  for (const [file,doc] of [...documents].sort(([a],[b])=>a.localeCompare(b))) {
    for (const [kind,entries] of Object.entries(doc.components ?? {})) {
      if (kind.startsWith('x-')) continue;
      contract.components[kind] ??= {};
      for (const [name,value] of Object.entries(entries)) {
        if (Object.hasOwn(contract.components[kind],name)) throw Error(`Duplicate component ${kind}/${name}`);
        contract.components[kind][name]=await normalize(value,file);
      }
    }
  }
  if (!Object.keys(contract.paths ?? {}).length || !Object.keys(contract.components.schemas ?? {}).length) throw Error('Empty contract');
  return { contract, sources: Object.fromEntries(Object.entries(sources).sort()) };
}

function makeAjv(schemas) {
  const ajv = new Ajv2020({ strictSchema:true, strictTypes:false, strictRequired:false, inlineRefs:false, code:{ source:true, esm:true }, allErrors:false });
  addFormats(ajv);
  const annotations=new Set();
  const collect=x=>{if(x&&typeof x==='object'){for(const [key,value] of Object.entries(x)){if(key.startsWith('x-'))annotations.add(key); collect(value);}}};
  collect(schemas);
  annotations.delete('x-lightnvr-max-bytes');
  for(const keyword of annotations)ajv.addKeyword({keyword,valid:true});
  ajv.addKeyword({ keyword:'x-lightnvr-max-bytes', type:'string', schemaType:'number',
    error:{message:'must fit the UTF-8 byte limit'},
    code(cxt){cxt.fail(_`new TextEncoder().encode(${cxt.data}).byteLength > ${cxt.schemaCode}`);}
  });
  // JSON Schema treats contentSchema as annotation. This boundary contract
  // explicitly enforces it, except the documented disabled empty string.
  ajv.removeKeyword('contentSchema');
  ajv.addKeyword({ keyword:'contentSchema', type:'string', schemaType:['object','boolean'],
    error:{message:'must contain valid JSON matching contentSchema (or be empty)'},
    code(cxt){
      const {gen,data}=cxt;
      gen.if(_`${data} !== ""`,()=>{
        const decoded=gen.let('decoded');
        const parsed=gen.let('parsed',true);
        gen.try(()=>gen.assign(decoded,_`JSON.parse(${data})`),()=>gen.assign(parsed,false));
        gen.if(parsed,()=>{
          const valid=gen.name('contentValid');
          cxt.subschema({keyword:'contentSchema',data:decoded},valid);
          gen.assign(parsed,valid);
        });
        cxt.pass(parsed);
      });
    }
  });
  return ajv;
}

// Keep human/source documentation in the OpenAPI artifact and TS output, not
// in shipped validators. Map-valued schema keywords preserve property names.
function runtimeSchema(value, map = false) {
  if (Array.isArray(value)) return value.map(x=>runtimeSchema(x));
  if (!value || typeof value !== 'object') return value;
  const output={};
  for (const [key,child] of Object.entries(value)) {
    if (!map && (['title','description','examples','example','deprecated','default','readOnly','writeOnly','externalDocs','xml'].includes(key) || (key.startsWith('x-') && key!=='x-lightnvr-max-bytes'))) continue;
    if (!map && ['const','enum','required','dependentRequired'].includes(key)) { output[key]=child; continue; }
    output[key]=runtimeSchema(child,!map && ['properties','patternProperties','$defs','definitions','dependentSchemas'].includes(key));
  }
  return output;
}

function schemaRefToId(value) {
  if(Array.isArray(value)) return value.map(schemaRefToId);
  if(!value || typeof value!=='object') return value;
  return Object.fromEntries(Object.entries(value).map(([key,child])=>{
    if(key==='$ref') {
      const prefix='#/components/schemas/';
      if(typeof child!=='string'||!child.startsWith(prefix))throw Error(`Non-schema ref in schema: ${child}`);
      const tokens=pointerTokens(child.slice(1));
      return [key,`urn:lightnvr:contract:${tokens[2]}`+(tokens.length>3?'#/'+tokens.slice(3).map(pointerEscape).join('/'):'')];
    }
    return [key,schemaRefToId(child)];
  }));
}

async function validateFixtures(root, ajv) {
  const folder=path.join(root,'tests/contracts/fixtures/streams');
  const manifest=JSON.parse(await fs.readFile(path.join(folder,'index.json'),'utf8'));
  if(!manifest.fixtures?.length)throw Error('No contract fixtures selected');
  const seen=new Set();
  for(const entry of manifest.fixtures) {
    if(seen.has(entry.file) || path.basename(entry.file)!==entry.file)throw Error(`Invalid fixture path: ${entry.file}`);
    seen.add(entry.file);
    const fixture=JSON.parse(await fs.readFile(path.join(folder,entry.file),'utf8'));
    if(fixture.schema!==entry.schema || fixture.expect!==entry.expect || !['valid','invalid'].includes(entry.expect)) throw Error(`Fixture metadata mismatch: ${entry.file}`);
    const name=entry.schema.split('/').at(-1);
    const validate=ajv.getSchema('urn:lightnvr:contract:'+name);
    if(!validate)throw Error(`Unknown fixture schema: ${entry.schema}`);
    const valid=validate(fixture.body);
    if(valid!==(entry.expect==='valid'))throw Error(`Fixture expectation failed: ${entry.file}: ${JSON.stringify(validate.errors)}`);
  }
  return seen.size;
}

export async function buildArtifacts({root=ROOT}={}) {
  const {contract,sources}=await loadContract(root);
  const schemas=contract.components.schemas;
  const names=Object.keys(schemas).sort();
  if(names.some(x=>!/^[$A-Z_a-z][$\w]*$/.test(x)))throw Error('Schema names must be JS identifiers');
  const ajv=makeAjv(schemas);
  for(const name of names) {
    const schema=schemaRefToId(runtimeSchema(schemas[name]));
    ajv.addSchema({...schema,$id:'urn:lightnvr:contract:'+name});
  }
  const exports={};
  for(const name of names) {
    const id='urn:lightnvr:contract:'+name;
    ajv.getSchema(id); // Compile every schema, including those without fixtures.
    exports['validate'+name]=id;
  }
  const fixtureCount=await validateFixtures(root,ajv);
  // Separate modules let consumers import one boundary without retaining every
  // Ajv validator's function-property assignments. The generated package marker
  // declares these modules side-effect-free outside their exported functions.
  const modules={};
  for(const name of names) {
    const standalone=standaloneCode(ajv,{['validate'+name]:exports['validate'+name]});
    const bundle=await build({stdin:{contents:standalone,resolveDir:ROOT,sourcefile:'validators.generated.mjs'},bundle:true,write:false,format:'esm',platform:'browser',target:'es2020',minify:true,legalComments:'none'});
    const runtime=HEADER+bundle.outputFiles[0].text;
    // Ajv helper metadata contains an inert require(...) string; executable
    // require calls would break browser/ESM loading and must not remain.
    if (/(?<!["'])\brequire\s*\(/.test(runtime)) throw Error('Unbundled require call in browser runtime');
    modules[`web/js/api/generated/validators/${name}.mjs`]=runtime;
    modules[`web/js/api/generated/validators/${name}.d.mts`]=HEADER+`export { validate${name} } from '../validators.mjs';\n`;
  }
  const runtime=HEADER+names.map(name=>`export { validate${name} } from './validators/${name}.mjs';`).join('\n')+'\n';
  const types=HEADER+astToString(await openapiTS(contract,{alphabetize:true}));
  const declaration=HEADER+`import type { components } from './types.js';\n\nexport interface ValidationIssue { readonly instancePath: string; readonly schemaPath: string; readonly keyword: string; readonly params: Readonly<Record<string, unknown>>; readonly message?: string; }\nexport interface ContractValidator<T> { (data: unknown): data is T; errors?: readonly ValidationIssue[] | null; }\n\n`+names.map(name=>`export const validate${name}: ContractValidator<components['schemas']['${name}']>;`).join('\n')+'\n';
  const operations={};
  for(const [url,item] of Object.entries(contract.paths)) {
    for(const [method,operation] of Object.entries(item)) {
      if(!METHODS.has(method))continue;
      if(!operation.operationId || operations[operation.operationId])throw Error('Missing/duplicate operationId');
      operations[operation.operationId]={method:method.toUpperCase(),path:url,success_statuses:Object.keys(operation.responses).map(Number).filter(x=>x>=200&&x<300).sort((a,b)=>a-b),responses:operation.responses,...(operation['x-lightnvr-response-variant-by-field']?{variant_by_field:operation['x-lightnvr-response-variant-by-field']}:{}) ,...(operation['x-lightnvr-response-variant-by-query']?{variant_by_query:operation['x-lightnvr-response-variant-by-query']}:{})};
    }
  }
  const artifacts={
    'web/js/api/generated/types.ts':types,
    'web/js/api/generated/validators.mjs':runtime,
    'web/js/api/generated/validators.d.mts':declaration,
    'tests/contracts/generated/openapi.json':JSON.stringify(contract,null,2)+'\n',
    'tests/contracts/generated/manifest.json':'',
    'web/js/api/generated/package.json':JSON.stringify({type:'module',sideEffects:false},null,2)+'\n',
    ...modules,
  };
  artifacts['tests/contracts/generated/manifest.json']=JSON.stringify({schema_version:1,sources,fixture_count:fixtureCount,owned_files:Object.keys(artifacts).sort(),schemas:Object.fromEntries(names.map(name=>[name,{validator:'validate'+name}])),operations},null,2)+'\n';
  return artifacts;
}

export async function writeArtifacts(root,artifacts) {
  for(const [name,text] of Object.entries(artifacts)) {
    const target=path.join(root,name);
    await fs.mkdir(path.dirname(target),{recursive:true});
    await fs.writeFile(target,text);
  }
}

async function filesUnder(root,relative) {
  const files=[];
  async function walk(dir) {
    let entries;
    try {entries=await fs.readdir(path.join(root,dir),{withFileTypes:true});} catch(error){if(error.code==='ENOENT')return;throw error;}
    for(const entry of entries) {
      const name=dir+'/'+entry.name;
      if(entry.isDirectory())await walk(name);else files.push(name);
    }
  }
  await walk(relative);
  return files;
}

export async function checkArtifacts(root,artifacts) {
  const errors=[];
  for(const [name,text] of Object.entries(artifacts)) {
    try{if(await fs.readFile(path.join(root,name),'utf8')!==text)errors.push(`stale generated file: ${name}`);}
    catch(error){if(error.code==='ENOENT')errors.push(`missing generated file: ${name}`);else throw error;}
  }
  for(const dir of GENERATED_DIRS)for(const name of await filesUnder(root,dir))if(!Object.hasOwn(artifacts,name))errors.push(`unexpected generated file: ${name}`);
  const git=spawnSync('git',['ls-files','--others','--exclude-standard','--',...GENERATED_DIRS],{cwd:root,encoding:'utf8'});
  if(git.status===0)for(const file of git.stdout.trim().split('\n').filter(Boolean))errors.push(`untracked generated file: ${file}`);
  return errors;
}

async function main() {
  const args=process.argv.slice(2);
  if(args.length!==1 || !['--generate','--check'].includes(args[0]))throw Error('Usage: node scripts/quality/contracts.mjs --generate|--check');
  const artifacts=await buildArtifacts();
  if(args[0]==='--generate') {
    await writeArtifacts(ROOT,artifacts);
    console.log(`Generated ${Object.keys(artifacts).length} contract artifacts; review and stage all generated paths before --check.`);
  } else {
    const temporary=await fs.mkdtemp(path.join(os.tmpdir(),'lightnvr-contract-check-'));
    try {
      await writeArtifacts(temporary,artifacts);
      const fresh=Object.fromEntries(await Promise.all(Object.keys(artifacts).map(async name=>[name,await fs.readFile(path.join(temporary,name),'utf8')])));
      const errors=await checkArtifacts(ROOT,fresh);
      if(errors.length)throw Error(errors.join('\n'));
      console.log(`Contract artifacts match (${Object.keys(artifacts).length} files).`);
    } finally {await fs.rm(temporary,{recursive:true,force:true});}
  }
}
if(process.argv[1] && path.resolve(process.argv[1])===fileURLToPath(import.meta.url))main().catch(error=>{console.error(error.message);process.exitCode=1;});
