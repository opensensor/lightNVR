unsafe extern "C" fn cleanup_stale_backup_artifacts(
    mut backup_dir: *const ::core::ffi::c_char,
) -> ::core::ffi::c_int {
    let mut dir: *mut DIR = opendir(backup_dir);
    if dir.is_null() {
        return if *__errno_location() == ENOENT {
            0 as ::core::ffi::c_int
        } else {
            -1 as ::core::ffi::c_int
        };
    }
    let mut result: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    let mut parent: ::core::ffi::c_int = dirfd(dir);
    if parent < 0 as ::core::ffi::c_int {
        closedir(dir);
        return -1 as ::core::ffi::c_int;
    }
    let mut entry: *mut dirent = ::core::ptr::null_mut::<dirent>();
    loop {
        entry = readdir(dir);
        if entry.is_null() {
            break;
        }
        if !(is_temporary_backup_artifact(&raw mut (*entry).d_name as *mut ::core::ffi::c_char)
            as ::core::ffi::c_int
            != 0
            && cleanup_stale_backup_entry(
                parent,
                backup_dir,
                &raw mut (*entry).d_name as *mut ::core::ffi::c_char,
            ) != 0 as ::core::ffi::c_int)
        {
            continue;
        }
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT,
            _log_stream_name,
            b"Incomplete stale backup cleanup: %s/%s\0".as_ptr() as *const ::core::ffi::c_char,
            backup_dir,
            &raw mut (*entry).d_name as *mut ::core::ffi::c_char,
        );
        result = -1 as ::core::ffi::c_int;
        break;
    }
    closedir(dir);
    return result;
}
unsafe extern "C" fn copy_file_contents(
    mut source_path: *const ::core::ffi::c_char,
    mut dest_path: *const ::core::ffi::c_char,
) -> ::core::ffi::c_int {
    let mut src_fd: ::core::ffi::c_int = -1 as ::core::ffi::c_int;
    let mut dst_fd: ::core::ffi::c_int = -1 as ::core::ffi::c_int;
    let mut buffer: [::core::ffi::c_char; 8192] = [0; 8192];
    src_fd = open(source_path, O_RDONLY);
    if src_fd < 0 as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to open source file for copy: %s (%s)\0".as_ptr()
                as *const ::core::ffi::c_char,
            source_path,
            strerror(*__errno_location()),
        );
        return -1 as ::core::ffi::c_int;
    }
    dst_fd = open(
        dest_path,
        O_WRONLY | O_CREAT | O_TRUNC,
        0o600 as ::core::ffi::c_int,
    );
    if dst_fd < 0 as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to open destination file for copy: %s (%s)\0".as_ptr()
                as *const ::core::ffi::c_char,
            dest_path,
            strerror(*__errno_location()),
        );
        close(src_fd);
        return -1 as ::core::ffi::c_int;
    }
    loop {
        let mut bytes_read: ssize_t = read(
            src_fd,
            &raw mut buffer as *mut ::core::ffi::c_char as *mut ::core::ffi::c_void,
            ::core::mem::size_of::<[::core::ffi::c_char; 8192]>(),
        );
        if bytes_read == 0 as ssize_t {
            break;
        }
        if bytes_read < 0 as ssize_t {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_ERROR,
                LOG_COMPONENT,
                _log_stream_name,
                b"Failed to read source file during copy: %s (%s)\0".as_ptr()
                    as *const ::core::ffi::c_char,
                source_path,
                strerror(*__errno_location()),
            );
            close(src_fd);
            close(dst_fd);
            return -1 as ::core::ffi::c_int;
        }
        let mut total_written: ssize_t = 0 as ssize_t;
        while total_written < bytes_read {
            let mut bytes_written: ssize_t = write(
                dst_fd,
                (&raw mut buffer as *mut ::core::ffi::c_char).offset(total_written as isize)
                    as *const ::core::ffi::c_void,
                (bytes_read - total_written) as size_t,
            );
            if bytes_written < 0 as ssize_t {
                _log_message_ctx(
                    log_level_t::LOG_LEVEL_ERROR,
                    LOG_COMPONENT,
                    _log_stream_name,
                    b"Failed to write destination file during copy: %s (%s)\0".as_ptr()
                        as *const ::core::ffi::c_char,
                    dest_path,
                    strerror(*__errno_location()),
                );
                close(src_fd);
                close(dst_fd);
                return -1 as ::core::ffi::c_int;
            }
            total_written += bytes_written;
        }
    }
    close(src_fd);
    close(dst_fd);
    return 0 as ::core::ffi::c_int;
}
unsafe extern "C" fn refresh_latest_backup(
    mut timestamped_backup_path: *const ::core::ffi::c_char,
) -> ::core::ffi::c_int {
    let mut temp_latest_path: [::core::ffi::c_char; 4096] = [0; 4096];
    if snprintf(
        &raw mut temp_latest_path as *mut ::core::ffi::c_char,
        ::core::mem::size_of::<[::core::ffi::c_char; 4096]>(),
        b"%s.tmp\0".as_ptr() as *const ::core::ffi::c_char,
        &raw mut db_backup_path as *mut ::core::ffi::c_char,
    ) >= ::core::mem::size_of::<[::core::ffi::c_char; 4096]>() as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Latest backup temp path is too long: %s\0".as_ptr() as *const ::core::ffi::c_char,
            &raw mut db_backup_path as *mut ::core::ffi::c_char,
        );
        return -1 as ::core::ffi::c_int;
    }
    unlink(&raw mut temp_latest_path as *mut ::core::ffi::c_char);
    if link(
        timestamped_backup_path,
        &raw mut temp_latest_path as *mut ::core::ffi::c_char,
    ) != 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to hard-link latest backup, falling back to copy: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            strerror(*__errno_location()),
        );
        if copy_file_contents(
            timestamped_backup_path,
            &raw mut temp_latest_path as *mut ::core::ffi::c_char,
        ) != 0 as ::core::ffi::c_int
        {
            unlink(&raw mut temp_latest_path as *mut ::core::ffi::c_char);
            return -1 as ::core::ffi::c_int;
        }
    }
    if rename(
        &raw mut temp_latest_path as *mut ::core::ffi::c_char,
        &raw mut db_backup_path as *mut ::core::ffi::c_char,
    ) != 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to publish latest backup %s -> %s: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            &raw mut temp_latest_path as *mut ::core::ffi::c_char,
            &raw mut db_backup_path as *mut ::core::ffi::c_char,
            strerror(*__errno_location()),
        );
        unlink(&raw mut temp_latest_path as *mut ::core::ffi::c_char);
        return -1 as ::core::ffi::c_int;
    }
    if sync_path_if_exists(&raw mut db_backup_path as *mut ::core::ffi::c_char)
        != 0 as ::core::ffi::c_int
        || sync_parent_directory(&raw mut db_backup_path as *mut ::core::ffi::c_char)
            != 0 as ::core::ffi::c_int
    {
        return -1 as ::core::ffi::c_int;
    }
    return 0 as ::core::ffi::c_int;
}
unsafe extern "C" fn compare_selected_backups(
    mut lhs: *const ::core::ffi::c_void,
    mut rhs: *const ::core::ffi::c_void,
) -> ::core::ffi::c_int {
    let mut left: *const selected_backup_t = lhs as *const selected_backup_t;
    let mut right: *const selected_backup_t = rhs as *const selected_backup_t;
    return strcmp((*left).name, (*right).name);
}
unsafe extern "C" fn prune_timestamped_backups(
    mut backup_dir: *const ::core::ffi::c_char,
    mut retention_count: ::core::ffi::c_int,
) -> ::core::ffi::c_int {
    let mut dir: *mut DIR = opendir(backup_dir);
    if dir.is_null() {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to open backup directory for pruning: %s (%s)\0".as_ptr()
                as *const ::core::ffi::c_char,
            backup_dir,
            strerror(*__errno_location()),
        );
        return -1 as ::core::ffi::c_int;
    }
    let mut parent: ::core::ffi::c_int = dirfd(dir);
    if parent < 0 as ::core::ffi::c_int {
        closedir(dir);
        return -1 as ::core::ffi::c_int;
    }
    let mut backups: *mut selected_backup_t = ::core::ptr::null_mut::<selected_backup_t>();
    let mut backup_count: size_t = 0 as size_t;
    let mut backup_capacity: size_t = 0 as size_t;
    let mut result: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    loop {
        *__errno_location() = 0 as ::core::ffi::c_int;
        let mut entry: *mut dirent = readdir(dir);
        if entry.is_null() {
            if *__errno_location() != 0 as ::core::ffi::c_int {
                result = -1 as ::core::ffi::c_int;
            }
            break;
        } else {
            if (*entry).d_name[0usize] as ::core::ffi::c_int == '.' as ::core::ffi::c_int
                || !has_suffix(
                    &raw mut (*entry).d_name as *mut ::core::ffi::c_char,
                    b".sqlite3\0".as_ptr() as *const ::core::ffi::c_char,
                )
            {
                continue;
            }
            let mut candidate: ::core::ffi::c_int = openat(
                parent,
                &raw mut (*entry).d_name as *mut ::core::ffi::c_char,
                O_PATH | O_NOFOLLOW | O_CLOEXEC,
            );
            if candidate < 0 as ::core::ffi::c_int {
                result = -1 as ::core::ffi::c_int;
                break;
            } else {
                let mut selected: stat = stat {
                    st_dev: 0,
                    st_ino: 0,
                    st_nlink: 0,
                    st_mode: 0,
                    st_uid: 0,
                    st_gid: 0,
                    __pad0: 0,
                    st_rdev: 0,
                    st_size: 0,
                    st_blksize: 0,
                    st_blocks: 0,
                    st_atim: timespec {
                        tv_sec: 0,
                        tv_nsec: 0,
                    },
                    st_mtim: timespec {
                        tv_sec: 0,
                        tv_nsec: 0,
                    },
                    st_ctim: timespec {
                        tv_sec: 0,
                        tv_nsec: 0,
                    },
                    __glibc_reserved: [0; 3],
                };
                if fstat(candidate, &raw mut selected) != 0 as ::core::ffi::c_int {
                    close(candidate);
                    result = -1 as ::core::ffi::c_int;
                    break;
                } else if !(selected.st_mode & __S_IFMT as __mode_t == 0o100000 as __mode_t) {
                    close(candidate);
                } else {
                    if backup_count == backup_capacity {
                        if backup_capacity > (SIZE_MAX as size_t).wrapping_div(2 as size_t) {
                            close(candidate);
                            result = -1 as ::core::ffi::c_int;
                            break;
                        } else {
                            let mut capacity: size_t = if backup_capacity != 0 {
                                backup_capacity.wrapping_mul(2 as size_t)
                            } else {
                                8 as size_t
                            };
                            if capacity
                                > (SIZE_MAX as usize)
                                    .wrapping_div(::core::mem::size_of::<selected_backup_t>())
                            {
                                close(candidate);
                                result = -1 as ::core::ffi::c_int;
                                break;
                            } else {
                                let mut grown: *mut selected_backup_t = realloc(
                                    backups as *mut ::core::ffi::c_void,
                                    capacity
                                        .wrapping_mul(::core::mem::size_of::<selected_backup_t>()),
                                )
                                    as *mut selected_backup_t;
                                if grown.is_null() {
                                    close(candidate);
                                    result = -1 as ::core::ffi::c_int;
                                    break;
                                } else {
                                    backups = grown;
                                    backup_capacity = capacity;
                                }
                            }
                        }
                    }
                    let mut name: *mut ::core::ffi::c_char =
                        strdup(&raw mut (*entry).d_name as *mut ::core::ffi::c_char);
                    if name.is_null() {
                        close(candidate);
                        result = -1 as ::core::ffi::c_int;
                        break;
                    } else {
                        let c2rust_fresh0 = backup_count;
                        backup_count = backup_count.wrapping_add(1);
                        *backups.offset(c2rust_fresh0 as isize) = selected_backup_t {
                            name: name,
                            fd: candidate,
                            selected: selected,
                        };
                    }
                }
            }
        }
    }
    if result == 0 as ::core::ffi::c_int && backup_count > 1 as size_t {
        qsort(
            backups as *mut ::core::ffi::c_void,
            backup_count,
            ::core::mem::size_of::<selected_backup_t>(),
            Some(
                compare_selected_backups
                    as unsafe extern "C" fn(
                        *const ::core::ffi::c_void,
                        *const ::core::ffi::c_void,
                    ) -> ::core::ffi::c_int,
            ),
        );
        let mut i: size_t = 1 as size_t;
        while i < backup_count {
            if strcmp(
                (*backups.offset(i.wrapping_sub(1 as size_t) as isize)).name,
                (*backups.offset(i as isize)).name,
            ) == 0 as ::core::ffi::c_int
            {
                result = -1 as ::core::ffi::c_int;
                break;
            } else {
                i = i.wrapping_add(1);
            }
        }
    }
    if result == 0 as ::core::ffi::c_int && backup_count > retention_count as size_t {
        let mut remove_count: size_t = backup_count.wrapping_sub(retention_count as size_t);
        let mut i_0: size_t = 0 as size_t;
        while i_0 < remove_count {
            if remove_pinned_backup_entry(
                parent,
                backup_dir,
                (*backups.offset(i_0 as isize)).name,
                (*backups.offset(i_0 as isize)).fd,
                &raw mut (*backups.offset(i_0 as isize)).selected,
                r#false != 0,
            ) != 0 as ::core::ffi::c_int
            {
                result = -1 as ::core::ffi::c_int;
                break;
            } else {
                close((*backups.offset(i_0 as isize)).fd);
                (*backups.offset(i_0 as isize)).fd = -1 as ::core::ffi::c_int;
                i_0 = i_0.wrapping_add(1);
            }
        }
    }
    let mut i_1: size_t = 0 as size_t;
    while i_1 < backup_count {
        if (*backups.offset(i_1 as isize)).fd >= 0 as ::core::ffi::c_int {
            close((*backups.offset(i_1 as isize)).fd);
        }
        free((*backups.offset(i_1 as isize)).name as *mut ::core::ffi::c_void);
        i_1 = i_1.wrapping_add(1);
    }
    free(backups as *mut ::core::ffi::c_void);
    if closedir(dir) != 0 as ::core::ffi::c_int {
        result = -1 as ::core::ffi::c_int;
    }
    if result != 0 as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT,
            _log_stream_name,
            b"Incomplete published backup retention: %s\0".as_ptr() as *const ::core::ffi::c_char,
            backup_dir,
        );
    }
    return result;
}
unsafe extern "C" fn run_post_backup_script(
    mut backup_path: *const ::core::ffi::c_char,
    mut backup_dir: *const ::core::ffi::c_char,
) -> ::core::ffi::c_int {
    if g_config.db_post_backup_script[0usize] as ::core::ffi::c_int == '\0' as ::core::ffi::c_int {
        return 0 as ::core::ffi::c_int;
    }
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Running post-backup script: %s\0".as_ptr() as *const ::core::ffi::c_char,
        &raw mut g_config.db_post_backup_script as *mut ::core::ffi::c_char,
    );
    let mut pid: pid_t = fork();
    if pid < 0 as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to fork post-backup script process: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            strerror(*__errno_location()),
        );
        return -1 as ::core::ffi::c_int;
    }
    if pid == 0 as ::core::ffi::c_int {
        let mut argv: [*const ::core::ffi::c_char; 5] = [
            &raw mut g_config.db_post_backup_script as *mut ::core::ffi::c_char
                as *const ::core::ffi::c_char,
            backup_path,
            &raw mut db_file_path as *mut ::core::ffi::c_char as *const ::core::ffi::c_char,
            backup_dir,
            ::core::ptr::null::<::core::ffi::c_char>(),
        ];
        execv(
            &raw mut g_config.db_post_backup_script as *mut ::core::ffi::c_char,
            &raw mut argv as *mut *const ::core::ffi::c_char as *const *mut ::core::ffi::c_char,
        );
        fprintf(
            stderr,
            b"Failed to execute post-backup script %s: %s\n\0".as_ptr()
                as *const ::core::ffi::c_char,
            &raw mut g_config.db_post_backup_script as *mut ::core::ffi::c_char,
            strerror(*__errno_location()),
        );
        _exit(127 as ::core::ffi::c_int);
    }
    let mut status: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    while waitpid(pid, &raw mut status, 0 as ::core::ffi::c_int) < 0 as ::core::ffi::c_int {
        if *__errno_location() != EINTR {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_ERROR,
                LOG_COMPONENT,
                _log_stream_name,
                b"waitpid failed for post-backup script: %s\0".as_ptr()
                    as *const ::core::ffi::c_char,
                strerror(*__errno_location()),
            );
            return -1 as ::core::ffi::c_int;
        }
    }
    if status & 0x7f as ::core::ffi::c_int == 0 as ::core::ffi::c_int
        && (status & 0xff00 as ::core::ffi::c_int) >> 8 as ::core::ffi::c_int
            == 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Post-backup script completed successfully\0".as_ptr() as *const ::core::ffi::c_char,
        );
        return 0 as ::core::ffi::c_int;
    }
    if status & 0x7f as ::core::ffi::c_int == 0 as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Post-backup script failed with exit code %d\0".as_ptr() as *const ::core::ffi::c_char,
            (status & 0xff00 as ::core::ffi::c_int) >> 8 as ::core::ffi::c_int,
        );
    } else if ((status & 0x7f as ::core::ffi::c_int) + 1 as ::core::ffi::c_int)
        as ::core::ffi::c_schar as ::core::ffi::c_int
        >> 1 as ::core::ffi::c_int
        > 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Post-backup script terminated by signal %d\0".as_ptr() as *const ::core::ffi::c_char,
            status & 0x7f as ::core::ffi::c_int,
        );
    } else {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Post-backup script did not complete successfully\0".as_ptr()
                as *const ::core::ffi::c_char,
        );
    }
    return -1 as ::core::ffi::c_int;
}
unsafe extern "C" fn perform_database_backup_cycle(
    mut reason: *const ::core::ffi::c_char,
    mut run_post_backup_hook: bool,
    mut abortable: bool,
) -> ::core::ffi::c_int {
    let mut backup_dir: [::core::ffi::c_char; 4096] = [0; 4096];
    let mut timestamped_backup_path: [::core::ffi::c_char; 4096] = [0; 4096];
    if db.is_null() || db_file_path[0usize] as ::core::ffi::c_int == '\0' as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Database not initialized, cannot create %s backup\0".as_ptr()
                as *const ::core::ffi::c_char,
            reason,
        );
        return -1 as ::core::ffi::c_int;
    }
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Starting %s database backup cycle\0".as_ptr() as *const ::core::ffi::c_char,
        reason,
    );
    if get_backup_directory(
        &raw mut backup_dir as *mut ::core::ffi::c_char,
        ::core::mem::size_of::<[::core::ffi::c_char; 4096]>(),
    ) != 0 as ::core::ffi::c_int
    {
        return -1 as ::core::ffi::c_int;
    }
    if build_timestamped_backup_path(
        &raw mut backup_dir as *mut ::core::ffi::c_char,
        &raw mut timestamped_backup_path as *mut ::core::ffi::c_char,
        ::core::mem::size_of::<[::core::ffi::c_char; 4096]>(),
    ) != 0 as ::core::ffi::c_int
    {
        return -1 as ::core::ffi::c_int;
    }
    if backup_database(
        &raw mut db_file_path as *mut ::core::ffi::c_char,
        &raw mut timestamped_backup_path as *mut ::core::ffi::c_char,
        abortable,
    ) != 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to create %s database backup\0".as_ptr() as *const ::core::ffi::c_char,
            reason,
        );
        return -1 as ::core::ffi::c_int;
    }
    if refresh_latest_backup(&raw mut timestamped_backup_path as *mut ::core::ffi::c_char)
        != 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to refresh latest backup link for %s backup\0".as_ptr()
                as *const ::core::ffi::c_char,
            reason,
        );
        return -1 as ::core::ffi::c_int;
    }
    if run_post_backup_hook as ::core::ffi::c_int != 0
        && g_config.db_post_backup_script[0usize] as ::core::ffi::c_int
            != '\0' as ::core::ffi::c_int
        && run_post_backup_script(
            &raw mut timestamped_backup_path as *mut ::core::ffi::c_char,
            &raw mut backup_dir as *mut ::core::ffi::c_char,
        ) != 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT,
            _log_stream_name,
            b"Post-backup script failed after %s backup\0".as_ptr() as *const ::core::ffi::c_char,
            reason,
        );
    }
    if prune_timestamped_backups(
        &raw mut backup_dir as *mut ::core::ffi::c_char,
        g_config.db_backup_retention_count,
    ) != 0 as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to fully enforce backup retention after %s backup\0".as_ptr()
                as *const ::core::ffi::c_char,
            reason,
        );
    }
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Completed %s database backup cycle: %s\0".as_ptr() as *const ::core::ffi::c_char,
        reason,
        &raw mut timestamped_backup_path as *mut ::core::ffi::c_char,
    );
    return 0 as ::core::ffi::c_int;
}
#[unsafe(no_mangle)]
pub unsafe extern "C" fn checkpoint_database() -> ::core::ffi::c_int {
    let mut rc: ::core::ffi::c_int = SQLITE_OK;
    if db.is_null() {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Database not initialized\0".as_ptr() as *const ::core::ffi::c_char,
        );
        return -1 as ::core::ffi::c_int;
    }
    if !wal_mode_enabled {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"WAL mode not enabled, no checkpoint needed\0".as_ptr() as *const ::core::ffi::c_char,
        );
        return 0 as ::core::ffi::c_int;
    }
    pthread_mutex_lock(&raw mut db_mutex);
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Checkpointing WAL file\0".as_ptr() as *const ::core::ffi::c_char,
    );
    rc = sqlite3_exec(
        db,
        b"PRAGMA wal_checkpoint(FULL);\0".as_ptr() as *const ::core::ffi::c_char,
        None,
        NULL,
        ::core::ptr::null_mut::<*mut ::core::ffi::c_char>(),
    );
    if rc != SQLITE_OK {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to checkpoint WAL: %s\0".as_ptr() as *const ::core::ffi::c_char,
            sqlite3_errmsg(db),
        );
        pthread_mutex_unlock(&raw mut db_mutex);
        return -1 as ::core::ffi::c_int;
    }
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"WAL checkpoint successful\0".as_ptr() as *const ::core::ffi::c_char,
    );
    pthread_mutex_unlock(&raw mut db_mutex);
    return 0 as ::core::ffi::c_int;
}
