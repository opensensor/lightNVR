#[unsafe(no_mangle)]
pub unsafe extern "C" fn db_scheduled_backup_wait_idle(mut timeout_ms: ::core::ffi::c_int) -> bool {
    pthread_once(
        &raw mut scheduled_backup_cond_once,
        Some(scheduled_backup_cond_init as unsafe extern "C" fn() -> ()),
    );
    let mut deadline: timespec = timespec {
        tv_sec: 0,
        tv_nsec: 0,
    };
    clock_gettime(scheduled_backup_cond_clock, &raw mut deadline);
    if timeout_ms > 0 as ::core::ffi::c_int {
        deadline.tv_sec += (timeout_ms / 1000 as ::core::ffi::c_int) as __time_t;
        deadline.tv_nsec += (timeout_ms % 1000 as ::core::ffi::c_int) as ::core::ffi::c_long
            * 1000000 as ::core::ffi::c_long;
        if deadline.tv_nsec >= 1000000000 as ::core::ffi::c_long {
            deadline.tv_sec += 1 as __time_t;
            deadline.tv_nsec -= 1000000000 as ::core::ffi::c_long;
        }
    }
    pthread_mutex_lock(&raw mut scheduled_backup_lock);
    while scheduled_backup_in_flight as ::core::ffi::c_int != 0
        && !scheduled_backup_abandoned
        && timeout_ms > 0 as ::core::ffi::c_int
    {
        if pthread_cond_timedwait(
            &raw mut scheduled_backup_cond,
            &raw mut scheduled_backup_lock,
            &raw mut deadline,
        ) == ETIMEDOUT
        {
            break;
        }
    }
    let mut idle: bool = !scheduled_backup_in_flight;
    if idle {
        reap_scheduled_backup_worker_locked();
    } else if timeout_ms > 0 as ::core::ffi::c_int && !scheduled_backup_abandoned {
        scheduled_backup_abandoned = r#true != 0;
        if scheduled_backup_thread_joinable {
            pthread_detach(scheduled_backup_thread);
            scheduled_backup_thread_joinable = r#false != 0;
        }
    }
    pthread_mutex_unlock(&raw mut scheduled_backup_lock);
    return idle;
}
unsafe extern "C" fn quiesce_scheduled_backup_worker() {
    pthread_mutex_lock(&raw mut scheduled_backup_lock);
    scheduled_backup_draining = r#true != 0;
    let mut in_flight: bool = scheduled_backup_in_flight;
    pthread_mutex_unlock(&raw mut scheduled_backup_lock);
    if in_flight {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Scheduled database backup still in flight; waiting up to %d s for it to stop\0"
                .as_ptr() as *const ::core::ffi::c_char,
            60 as ::core::ffi::c_int * 1000 as ::core::ffi::c_int / 1000 as ::core::ffi::c_int,
        );
        db_backup_request_cancel();
        if !db_scheduled_backup_wait_idle(DB_SCHEDULED_BACKUP_JOIN_TIMEOUT_MS) {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_ERROR,
                LOG_COMPONENT,
                _log_stream_name,
                b"Scheduled database backup worker has not stopped within its %d s budget; closing the database anyway\0"
                    .as_ptr() as *const ::core::ffi::c_char,
                60 as ::core::ffi::c_int * 1000 as ::core::ffi::c_int
                    / 1000 as ::core::ffi::c_int,
            );
            return;
        }
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"In-flight scheduled database backup stopped\0".as_ptr() as *const ::core::ffi::c_char,
        );
    } else {
        db_scheduled_backup_wait_idle(0 as ::core::ffi::c_int);
    }
    db_backup_clear_cancel();
}
#[unsafe(no_mangle)]
pub unsafe extern "C" fn maybe_run_scheduled_database_backup() -> ::core::ffi::c_int {
    if db.is_null() || db_file_path[0usize] as ::core::ffi::c_int == '\0' as ::core::ffi::c_int {
        return 0 as ::core::ffi::c_int;
    }
    if g_config.db_backup_interval_minutes <= 0 as ::core::ffi::c_int {
        return 0 as ::core::ffi::c_int;
    }
    if is_background_abort_requested() {
        return 0 as ::core::ffi::c_int;
    }
    pthread_once(
        &raw mut scheduled_backup_cond_once,
        Some(scheduled_backup_cond_init as unsafe extern "C" fn() -> ()),
    );
    pthread_mutex_lock(&raw mut scheduled_backup_lock);
    if scheduled_backup_in_flight {
        pthread_mutex_unlock(&raw mut scheduled_backup_lock);
        return 0 as ::core::ffi::c_int;
    }
    reap_scheduled_backup_worker_locked();
    if scheduled_backup_draining {
        pthread_mutex_unlock(&raw mut scheduled_backup_lock);
        return 0 as ::core::ffi::c_int;
    }
    let mut now: time_t = time(::core::ptr::null_mut::<time_t>());
    let mut interval_seconds: time_t = g_config.db_backup_interval_minutes as time_t * 60 as time_t;
    let mut last_cycle: time_t = if last_scheduled_backup_finished > last_backup_time {
        last_scheduled_backup_finished
    } else {
        last_backup_time
    };
    if last_cycle != 0 as time_t && now - last_cycle < interval_seconds {
        pthread_mutex_unlock(&raw mut scheduled_backup_lock);
        return 0 as ::core::ffi::c_int;
    }
    db_backup_clear_cancel();
    scheduled_backup_in_flight = r#true != 0;
    scheduled_backup_abandoned = r#false != 0;
    let mut rc: ::core::ffi::c_int = pthread_create(
        &raw mut scheduled_backup_thread,
        ::core::ptr::null::<pthread_attr_t>(),
        Some(
            scheduled_backup_thread_main
                as unsafe extern "C" fn(*mut ::core::ffi::c_void) -> *mut ::core::ffi::c_void,
        ),
        NULL,
    );
    if rc != 0 as ::core::ffi::c_int {
        scheduled_backup_in_flight = r#false != 0;
        last_scheduled_backup_finished = now;
        pthread_mutex_unlock(&raw mut scheduled_backup_lock);
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to start scheduled database backup thread: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            strerror(rc),
        );
        return -1 as ::core::ffi::c_int;
    }
    scheduled_backup_thread_joinable = r#true != 0;
    pthread_mutex_unlock(&raw mut scheduled_backup_lock);
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Scheduled database backup started in background\0".as_ptr() as *const ::core::ffi::c_char,
    );
    return 1 as ::core::ffi::c_int;
}
