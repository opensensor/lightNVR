#[unsafe(no_mangle)]
pub unsafe extern "C" fn shutdown_database() {
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Starting database shutdown process\0".as_ptr() as *const ::core::ffi::c_char,
    );
    quiesce_scheduled_backup_worker();
    let mut backup_interval_seconds: time_t =
        if g_config.db_backup_interval_minutes > 0 as ::core::ffi::c_int {
            g_config.db_backup_interval_minutes as time_t * 60 as time_t
        } else {
            0 as time_t
        };
    let mut now: time_t = time(::core::ptr::null_mut::<time_t>());
    pthread_mutex_lock(&raw mut scheduled_backup_lock);
    let mut last_backup_snapshot: time_t = last_backup_time;
    pthread_mutex_unlock(&raw mut scheduled_backup_lock);
    let mut recent_backup_exists: bool = backup_interval_seconds > 0 as time_t
        && last_backup_snapshot != 0 as time_t
        && now >= last_backup_snapshot
        && now - last_backup_snapshot < backup_interval_seconds;
    if db_init_flags & C2Rust_Unnamed_1::DB_INIT_NO_BACKUP.0 != 0 {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Skipping shutdown backup (read-only initialization)\0".as_ptr()
                as *const ::core::ffi::c_char,
        );
    } else if recent_backup_exists {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Skipping final backup: last backup was %ld seconds ago, within the %d-minute scheduled interval\0"
                .as_ptr() as *const ::core::ffi::c_char,
            now - last_backup_snapshot,
            g_config.db_backup_interval_minutes,
        );
    } else if !db.is_null()
        && db_file_path[0usize] as ::core::ffi::c_int != '\0' as ::core::ffi::c_int
    {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Creating final backup before shutdown\0".as_ptr() as *const ::core::ffi::c_char,
        );
        if perform_database_backup_cycle(
            b"shutdown\0".as_ptr() as *const ::core::ffi::c_char,
            r#true != 0,
            r#false != 0,
        ) == 0 as ::core::ffi::c_int
        {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Final backup created successfully\0".as_ptr() as *const ::core::ffi::c_char,
            );
        } else {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_WARN,
                LOG_COMPONENT,
                _log_stream_name,
                b"Failed to create final backup\0".as_ptr() as *const ::core::ffi::c_char,
            );
        }
    }
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Waiting for in-flight database operations before shutdown\0".as_ptr()
            as *const ::core::ffi::c_char,
    );
    pthread_mutex_lock(&raw mut db_mutex);
    if !db.is_null() {
        let mut db_to_close: *mut sqlite3 = db;
        if wal_mode_enabled {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Checkpointing WAL before closing database\0".as_ptr()
                    as *const ::core::ffi::c_char,
            );
            let mut rc: ::core::ffi::c_int = sqlite3_exec(
                db_to_close,
                b"PRAGMA wal_checkpoint(FULL);\0".as_ptr() as *const ::core::ffi::c_char,
                None,
                NULL,
                ::core::ptr::null_mut::<*mut ::core::ffi::c_char>(),
            );
            if rc != SQLITE_OK {
                _log_message_ctx(
                    log_level_t::LOG_LEVEL_WARN,
                    LOG_COMPONENT,
                    _log_stream_name,
                    b"Failed to checkpoint WAL: %s\0".as_ptr() as *const ::core::ffi::c_char,
                    sqlite3_errmsg(db_to_close),
                );
            } else {
                _log_message_ctx(
                    log_level_t::LOG_LEVEL_INFO,
                    LOG_COMPONENT,
                    _log_stream_name,
                    b"WAL checkpoint successful\0".as_ptr() as *const ::core::ffi::c_char,
                );
            }
        }
        let mut stmt_count: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
        let mut stmt: *mut sqlite3_stmt = ::core::ptr::null_mut::<sqlite3_stmt>();
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Finalizing all prepared statements\0".as_ptr() as *const ::core::ffi::c_char,
        );
        loop {
            stmt = sqlite3_next_stmt(db_to_close, ::core::ptr::null_mut::<sqlite3_stmt>());
            if stmt.is_null() {
                break;
            }
            stmt_count += 1;
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Finalizing prepared statement %d during database shutdown\0".as_ptr()
                    as *const ::core::ffi::c_char,
                stmt_count,
            );
            sqlite3_finalize(stmt);
        }
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Finalized %d prepared statements\0".as_ptr() as *const ::core::ffi::c_char,
            stmt_count,
        );
        stmt_count = 0 as ::core::ffi::c_int;
        loop {
            stmt = sqlite3_next_stmt(db_to_close, ::core::ptr::null_mut::<sqlite3_stmt>());
            if stmt.is_null() {
                break;
            }
            stmt_count += 1;
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Finalizing remaining statement %d in second pass\0".as_ptr()
                    as *const ::core::ffi::c_char,
                stmt_count,
            );
            sqlite3_finalize(stmt);
        }
        if stmt_count > 0 as ::core::ffi::c_int {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Finalized %d additional statements in second pass\0".as_ptr()
                    as *const ::core::ffi::c_char,
                stmt_count,
            );
        }
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Releasing cached schema resources\0".as_ptr() as *const ::core::ffi::c_char,
        );
        sqlite3_exec(
            db_to_close,
            b"PRAGMA schema_version;\0".as_ptr() as *const ::core::ffi::c_char,
            None,
            NULL,
            ::core::ptr::null_mut::<*mut ::core::ffi::c_char>(),
        );
        _log_message_ctx(
            log_level_t::LOG_LEVEL_INFO,
            LOG_COMPONENT,
            _log_stream_name,
            b"Closing database with sqlite3_close_v2\0".as_ptr() as *const ::core::ffi::c_char,
        );
        let mut rc_0: ::core::ffi::c_int = sqlite3_close_v2(db_to_close);
        if rc_0 != SQLITE_OK {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_WARN,
                LOG_COMPONENT,
                _log_stream_name,
                b"Error closing database: %s (code: %d)\0".as_ptr() as *const ::core::ffi::c_char,
                sqlite3_errmsg(db_to_close),
                rc_0,
            );
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Attempting to finalize any remaining statements\0".as_ptr()
                    as *const ::core::ffi::c_char,
            );
            stmt_count = 0 as ::core::ffi::c_int;
            loop {
                stmt = sqlite3_next_stmt(db_to_close, ::core::ptr::null_mut::<sqlite3_stmt>());
                if stmt.is_null() {
                    break;
                }
                stmt_count += 1;
                _log_message_ctx(
                    log_level_t::LOG_LEVEL_INFO,
                    LOG_COMPONENT,
                    _log_stream_name,
                    b"Finalizing remaining statement %d in error recovery\0".as_ptr()
                        as *const ::core::ffi::c_char,
                    stmt_count,
                );
                sqlite3_finalize(stmt);
            }
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Retrying database close\0".as_ptr() as *const ::core::ffi::c_char,
            );
            rc_0 = sqlite3_close_v2(db_to_close);
            if rc_0 != SQLITE_OK {
                _log_message_ctx(
                    log_level_t::LOG_LEVEL_ERROR,
                    LOG_COMPONENT,
                    _log_stream_name,
                    b"Failed to close database after retry: %s (code: %d)\0".as_ptr()
                        as *const ::core::ffi::c_char,
                    sqlite3_errmsg(db_to_close),
                    rc_0,
                );
            } else {
                _log_message_ctx(
                    log_level_t::LOG_LEVEL_INFO,
                    LOG_COMPONENT,
                    _log_stream_name,
                    b"Successfully closed database on retry\0".as_ptr()
                        as *const ::core::ffi::c_char,
                );
            }
        } else {
            _log_message_ctx(
                log_level_t::LOG_LEVEL_INFO,
                LOG_COMPONENT,
                _log_stream_name,
                b"Successfully closed database\0".as_ptr() as *const ::core::ffi::c_char,
            );
        }
        db = ::core::ptr::null_mut::<sqlite3>();
        reset_sqlite_internal_state();
    } else {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT,
            _log_stream_name,
            b"Database handle is already NULL during shutdown\0".as_ptr()
                as *const ::core::ffi::c_char,
        );
    }
    pthread_mutex_unlock(&raw mut db_mutex);
    sqlite3_shutdown();
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT,
        _log_stream_name,
        b"Database shutdown complete\0".as_ptr() as *const ::core::ffi::c_char,
    );
}
