#[unsafe(no_mangle)]
pub unsafe extern "C" fn db_open_readonly_connection(
    mut connection: *mut *mut sqlite3,
) -> ::core::ffi::c_int {
    if connection.is_null() {
        return -1 as ::core::ffi::c_int;
    }
    *connection = ::core::ptr::null_mut::<sqlite3>();
    if db_file_path[0usize] as ::core::ffi::c_int == '\0' as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Cannot open read-only database connection before initialization\0".as_ptr()
                as *const ::core::ffi::c_char,
        );
        return -1 as ::core::ffi::c_int;
    }
    let mut rc: ::core::ffi::c_int = sqlite3_open_v2(
        &raw mut db_file_path as *mut ::core::ffi::c_char,
        connection,
        SQLITE_OPEN_READONLY | SQLITE_OPEN_NOMUTEX | SQLITE_OPEN_PRIVATECACHE,
        ::core::ptr::null::<::core::ffi::c_char>(),
    );
    if rc != SQLITE_OK {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to open read-only database connection: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            if !(*connection).is_null() {
                sqlite3_errmsg(*connection)
            } else {
                b"unknown error\0".as_ptr() as *const ::core::ffi::c_char
            },
        );
        if !(*connection).is_null() {
            sqlite3_close_v2(*connection);
        }
        *connection = ::core::ptr::null_mut::<sqlite3>();
        return -1 as ::core::ffi::c_int;
    }
    let mut persist_wal: ::core::ffi::c_int = 1 as ::core::ffi::c_int;
    let mut persist_rc: ::core::ffi::c_int = sqlite3_file_control(
        *connection,
        b"main\0".as_ptr() as *const ::core::ffi::c_char,
        SQLITE_FCNTL_PERSIST_WAL,
        &raw mut persist_wal as *mut ::core::ffi::c_void,
    );
    if persist_rc != SQLITE_OK && persist_rc != SQLITE_NOTFOUND {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to preserve WAL sidecars for read-only connection: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            sqlite3_errstr(persist_rc),
        );
    }
    sqlite3_busy_timeout(*connection, 10000 as ::core::ffi::c_int);
    rc = sqlite3_exec(
        *connection,
        b"PRAGMA query_only=ON;\0".as_ptr() as *const ::core::ffi::c_char,
        None,
        NULL,
        ::core::ptr::null_mut::<*mut ::core::ffi::c_char>(),
    );
    if rc != SQLITE_OK {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT,
            _log_stream_name,
            b"Failed to configure read-only database connection: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            sqlite3_errmsg(*connection),
        );
        sqlite3_close_v2(*connection);
        *connection = ::core::ptr::null_mut::<sqlite3>();
        return -1 as ::core::ffi::c_int;
    }
    return 0 as ::core::ffi::c_int;
}
