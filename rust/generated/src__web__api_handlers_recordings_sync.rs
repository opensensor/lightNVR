    unsafe { ::core::mem::transmute::<[u8; 14], [::core::ffi::c_char; 14]>(*b"RecordingsAPI\0") };
pub const _log_stream_name: *const ::core::ffi::c_char = NULL as *const ::core::ffi::c_char;
#[unsafe(no_mangle)]
pub unsafe extern "C" fn handle_post_recordings_sync(
    mut req: *const http_request_t,
    mut res: *mut http_response_t,
) {
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT.as_ptr(),
        _log_stream_name,
        b"Processing POST /api/recordings/sync request\0".as_ptr() as *const ::core::ffi::c_char,
    );
    let mut user: user_t = user_t {
        id: 0,
        username: [0; 64],
        email: [0; 128],
        role: user_role_t::USER_ROLE_ADMIN,
        api_key: [0; 64],
        created_at: 0,
        updated_at: 0,
        last_login: 0,
        is_active: false,
        password_change_locked: false,
        must_change_password: false,
        totp_enabled: false,
        allowed_login_cidrs: [0; 1024],
        has_login_cidr_restriction: false,
        authorization_mode: [0; 16],
        authenticated_via_scoped_token: false,
        api_token_uuid: [0; 37],
        authentication_method: [0; 24],
    };
    let mut evaluation: authorization_evaluation_t = authorization_evaluation_t {
        decision: authorization_decision_t::AUTHZ_DECISION_DENY,
        source: authorization_decision_source_t::AUTHZ_SOURCE_NONE,
        policy_version: 0,
        grant_uuid: [0; 37],
        token_uuid: [0; 37],
        role_uuid: [0; 37],
        role_name: [0; 128],
        explanation: [0; 256],
    };
    if httpd_authorize_action(
        req,
        res,
        authorization_action_t::AUTHZ_STORAGE_CONFIGURE,
        ::core::ptr::null::<fleet_camera_t>(),
        &raw mut user,
        &raw mut evaluation,
    ) == 0
    {
        return;
    }
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT.as_ptr(),
        _log_stream_name,
        b"Triggering recording file size sync\0".as_ptr() as *const ::core::ffi::c_char,
    );
    let mut result: ::core::ffi::c_int = force_recording_sync();
    if result < 0 as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT.as_ptr(),
            _log_stream_name,
            b"Recording sync failed\0".as_ptr() as *const ::core::ffi::c_char,
        );
        http_response_set_json_error(
            res,
            500 as ::core::ffi::c_int,
            b"Recording sync failed\0".as_ptr() as *const ::core::ffi::c_char,
        );
        audit_log_operation(
            req,
            &raw mut user,
            b"storage.configure\0".as_ptr() as *const ::core::ffi::c_char,
            b"recordings\0".as_ptr() as *const ::core::ffi::c_char,
            ::core::ptr::null::<::core::ffi::c_char>(),
            b"recordings.sync\0".as_ptr() as *const ::core::ffi::c_char,
            b"error\0".as_ptr() as *const ::core::ffi::c_char,
            ::core::ptr::null::<cJSON>(),
        );
        return;
    }
    let mut response: [::core::ffi::c_char; 256] = [0; 256];
    snprintf(
        &raw mut response as *mut ::core::ffi::c_char,
        ::core::mem::size_of::<[::core::ffi::c_char; 256]>(),
        b"{\"success\":true,\"message\":\"Recording sync complete\",\"updated\":%d}\0".as_ptr()
            as *const ::core::ffi::c_char,
        result,
    );
    http_response_set_json(
        res,
        200 as ::core::ffi::c_int,
        &raw mut response as *mut ::core::ffi::c_char,
    );
    let mut context: *mut cJSON = cJSON_CreateObject();
    if !context.is_null() {
        cJSON_AddNumberToObject(
            context,
            b"updated\0".as_ptr() as *const ::core::ffi::c_char,
            result as ::core::ffi::c_double,
        );
    }
    audit_log_operation(
        req,
        &raw mut user,
        b"storage.configure\0".as_ptr() as *const ::core::ffi::c_char,
        b"recordings\0".as_ptr() as *const ::core::ffi::c_char,
        ::core::ptr::null::<::core::ffi::c_char>(),
        b"recordings.sync\0".as_ptr() as *const ::core::ffi::c_char,
        b"success\0".as_ptr() as *const ::core::ffi::c_char,
        context,
    );
    cJSON_Delete(context);
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT.as_ptr(),
        _log_stream_name,
        b"Recording sync complete: %d recordings updated\0".as_ptr() as *const ::core::ffi::c_char,
        result,
    );
}
