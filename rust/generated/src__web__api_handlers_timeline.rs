unsafe extern "C" fn closest_timeline_segment(
    mut segments: *const timeline_segment_t,
    mut count: ::core::ffi::c_int,
    mut start_time: time_t,
) -> ::core::ffi::c_int {
    let mut selected: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    let mut min_distance: ::core::ffi::c_double = -1 as ::core::ffi::c_int as ::core::ffi::c_double;
    let mut i: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    while i < count {
        if start_time >= (*segments.offset(i as isize)).start_time
            && start_time <= (*segments.offset(i as isize)).end_time
        {
            return i;
        }
        let mut distance: ::core::ffi::c_double =
            if start_time < (*segments.offset(i as isize)).start_time {
                difftime((*segments.offset(i as isize)).start_time, start_time)
            } else {
                difftime(start_time, (*segments.offset(i as isize)).end_time)
            };
        if min_distance < 0 as ::core::ffi::c_int as ::core::ffi::c_double
            || distance < min_distance
        {
            min_distance = distance;
            selected = i;
        }
        i += 1;
    }
    return selected;
}
