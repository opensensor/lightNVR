#[unsafe(no_mangle)]
pub unsafe extern "C" fn create_timeline_manifest(
    mut segments: *const timeline_segment_t,
    mut segment_count: ::core::ffi::c_int,
    mut start_time: time_t,
    mut manifest_path: *mut ::core::ffi::c_char,
) -> ::core::ffi::c_int {
    if segments.is_null() || segment_count <= 0 as ::core::ffi::c_int || manifest_path.is_null() {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT.as_ptr(),
            _log_stream_name,
            b"Invalid parameters for create_timeline_manifest\0".as_ptr()
                as *const ::core::ffi::c_char,
        );
        return -1 as ::core::ffi::c_int;
    }
    if segment_count > MAX_MANIFEST_SEGMENTS {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_WARN,
            LOG_COMPONENT.as_ptr(),
            _log_stream_name,
            b"Limiting manifest to %d segments (requested %d)\0".as_ptr()
                as *const ::core::ffi::c_char,
            100 as ::core::ffi::c_int,
            segment_count,
        );
        segment_count = MAX_MANIFEST_SEGMENTS;
    }
    let mut selected: ::core::ffi::c_int =
        closest_timeline_segment(segments, segment_count, start_time);
    let mut temp_dir: [::core::ffi::c_char; 512] = [0; 512];
    snprintf(
        &raw mut temp_dir as *mut ::core::ffi::c_char,
        ::core::mem::size_of::<[::core::ffi::c_char; 512]>(),
        b"%s/timeline_manifests\0".as_ptr() as *const ::core::ffi::c_char,
        &raw mut g_config.storage_path as *mut ::core::ffi::c_char,
    );
    if ensure_dir(&raw mut temp_dir as *mut ::core::ffi::c_char) != 0 {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT.as_ptr(),
            _log_stream_name,
            b"Could not create directory for timeline manifest %s: %s\0".as_ptr()
                as *const ::core::ffi::c_char,
            &raw mut temp_dir as *mut ::core::ffi::c_char,
            strerror(*__errno_location()),
        );
        return -1 as ::core::ffi::c_int;
    }
    let mut manifest_filename: [::core::ffi::c_char; 512] = [0; 512];
    snprintf(
        &raw mut manifest_filename as *mut ::core::ffi::c_char,
        ::core::mem::size_of::<[::core::ffi::c_char; 512]>(),
        b"%s/manifest_%ld_%llu_%ld.m3u8\0".as_ptr() as *const ::core::ffi::c_char,
        &raw mut temp_dir as *mut ::core::ffi::c_char,
        time(::core::ptr::null_mut::<time_t>()),
        (*segments.offset(selected as isize)).id as ::core::ffi::c_ulonglong,
        start_time,
    );
    pthread_mutex_lock(&raw mut manifest_mutex);
    let mut manifest_fd: ::core::ffi::c_int = open(
        &raw mut manifest_filename as *mut ::core::ffi::c_char,
        O_WRONLY | O_CREAT | O_TRUNC,
        0o600 as ::core::ffi::c_int,
    );
    if manifest_fd < 0 as ::core::ffi::c_int {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT.as_ptr(),
            _log_stream_name,
            b"Failed to create manifest file: %s\0".as_ptr() as *const ::core::ffi::c_char,
            &raw mut manifest_filename as *mut ::core::ffi::c_char,
        );
        pthread_mutex_unlock(&raw mut manifest_mutex);
        return -1 as ::core::ffi::c_int;
    }
    let mut manifest: *mut FILE =
        fdopen(manifest_fd, b"w\0".as_ptr() as *const ::core::ffi::c_char);
    if manifest.is_null() {
        _log_message_ctx(
            log_level_t::LOG_LEVEL_ERROR,
            LOG_COMPONENT.as_ptr(),
            _log_stream_name,
            b"Failed to open manifest file stream: %s\0".as_ptr() as *const ::core::ffi::c_char,
            &raw mut manifest_filename as *mut ::core::ffi::c_char,
        );
        close(manifest_fd);
        pthread_mutex_unlock(&raw mut manifest_mutex);
        return -1 as ::core::ffi::c_int;
    }
    fprintf(
        manifest,
        b"#EXTM3U\n\0".as_ptr() as *const ::core::ffi::c_char,
    );
    fprintf(
        manifest,
        b"#EXT-X-VERSION:3\n\0".as_ptr() as *const ::core::ffi::c_char,
    );
    fprintf(
        manifest,
        b"#EXT-X-MEDIA-SEQUENCE:0\n\0".as_ptr() as *const ::core::ffi::c_char,
    );
    fprintf(
        manifest,
        b"#EXT-X-ALLOW-CACHE:YES\n\0".as_ptr() as *const ::core::ffi::c_char,
    );
    let mut duration: ::core::ffi::c_double = difftime(
        (*segments.offset(selected as isize)).end_time,
        (*segments.offset(selected as isize)).start_time,
    );
    let mut target_duration: ::core::ffi::c_int =
        duration as ::core::ffi::c_int + 1 as ::core::ffi::c_int;
    fprintf(
        manifest,
        b"#EXT-X-TARGETDURATION:%d\n\0".as_ptr() as *const ::core::ffi::c_char,
        target_duration,
    );
    fprintf(
        manifest,
        b"#EXTINF:%.6f,\n\0".as_ptr() as *const ::core::ffi::c_char,
        duration,
    );
    fprintf(
        manifest,
        b"/api/recordings/play/%llu\n\0".as_ptr() as *const ::core::ffi::c_char,
        (*segments.offset(selected as isize)).id as ::core::ffi::c_ulonglong,
    );
    fprintf(
        manifest,
        b"#EXT-X-ENDLIST\n\0".as_ptr() as *const ::core::ffi::c_char,
    );
    fclose(manifest);
    safe_strcpy(
        manifest_path,
        &raw mut manifest_filename as *mut ::core::ffi::c_char,
        MAX_PATH_LENGTH as size_t,
        0 as size_t,
    );
    pthread_mutex_unlock(&raw mut manifest_mutex);
    _log_message_ctx(
        log_level_t::LOG_LEVEL_INFO,
        LOG_COMPONENT.as_ptr(),
        _log_stream_name,
        b"Created timeline manifest: %s\0".as_ptr() as *const ::core::ffi::c_char,
        &raw mut manifest_filename as *mut ::core::ffi::c_char,
    );
    return 0 as ::core::ffi::c_int;
}
